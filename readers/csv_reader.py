def plot_vars(sgname, t, y, lbl, fname=None, xmin=None, xmax=None, 
              ymin=None, ymax=None, legend=True, color='blue'):
    """
    Plot signal data with consistent formatting.
    
    Args:
        sgname: Signal name (ylabel)
        t: Time array
        y: Values array
        lbl: Label text (or list of labels)
        fname: Optional output filename (saves as PDF)
        xmin, xmax: X-axis limits
        ymin, ymax: Y-axis limits
        legend: Show legend
        color: Default line color
    """
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not available for plotting")
        return None, None
    
    # Apply format (from pscad_reader.py)
    def format_axes(ax):
        for spine in ['top', 'right']:
            ax.spines[spine].set_visible(False)
        for spine in ['left', 'bottom']:
            ax.spines[spine].set_linewidth(0.5)
        ax.xaxis.set_ticks_position('bottom')
        ax.yaxis.set_ticks_position('left')
        ax.grid(linestyle=':')
        for axis in [ax.xaxis, ax.yaxis]:
            ax.tick_params(length=0)
        return ax
    
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(t, y, color=color, linewidth=0.8)
    ax.set_ylabel(sgname)
    ax.set_xlabel('Time (s)')
    
    if xmin is not None and xmax is not None:
        ax.set_xlim(xmin, xmax)
    if ymin is not None and ymax is not None:
        ax.set_ylim(ymin, ymax)
    
    if legend:
        lbl_text = lbl if isinstance(lbl, str) else lbl[0]
        ax.legend(loc='best', fontsize=8)
    ax.grid(True, alpha=0.3)
    
    try:
        plt.tight_layout()
    except:
        pass
    
    # Save if filename provided
    if fname:
        fig.savefig(f"{fname}.png", dpi=150, bbox_inches='tight')
        print(f"Saved: {fname}.png")
    
    return fig, ax


